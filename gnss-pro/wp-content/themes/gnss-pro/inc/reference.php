        ['Несущая', 'Радиоволна, на которую посажен код. По фазе несущей координату считают гораздо тоньше, чем по коду, но появляется целочисленная неоднозначность.'],
        ['Эфемериды', 'Оперативные данные о положении спутника и его часах. Приёмник читает их из сигнала. Для PPP берут уточнённые эфемериды служб, а не только бортовую закладку.'],
        ['Альманах', 'Грубый прогноз всей группировки. Нужен, чтобы приёмник знал, кого искать. Для сантиметровой работы альманаха недостаточно.'],
        ['FDMA', 'Частотное разделение: у разных аппаратов ГЛОНАСС открытый сигнал сидит на соседних литерах вокруг 1 602 и 1 246 МГц. Историческая особенность системы.'],
        ['CDMA', 'Кодовое разделение: аппараты передают на одной частоте и различаются кодами. Так устроены GPS, Galileo, BeiDou и новые сигналы ГЛОНАСС-К.'],
        ['Ионосфера', 'Ионизированный слой, который задерживает код и ускоряет фазу. Задержка падает с квадратом частоты, поэтому связка L1+L2 снимает её первую составляющую.'],
        ['DOP', 'Геометрический фактор. Даже идеальные часы дадут плохую координату, если все спутники сгрудились в одной части неба. Маленький DOP — удачная геометрия.'],
        ['Маска', 'Угол над горизонтом, ниже которого измерения отбрасывают. Низкий спутник светит через толстую атмосферу и цепляет переотражения.'],
        ['RTK', 'Кинематика в реальном времени. Ровер уточняет фазу по поправкам близкой базы и получает сантиметры, пока связь с базой жива и неоднозначность разрешена.'],
        ['PPP', 'Абсолютное точное позиционирование по уточнённым орбитам и часам, без местной базы. Сходимость занимает время, зато база не нужна.'],
        ['NTRIP', 'Протокол раздачи потока поправок через интернет. Так сетевой RTK доезжает до ровера.'],
        ['SBAS', 'Спутниковая система дифференциальных поправок и контроля целостности. Поправки идут с геостационарного аппарата. Точность лучше бытовой, но это не сетевой RTK.'],
        ['СДКМ', 'Российская система дифференциальной коррекции и мониторинга: наземная сеть плюс ретрансляция поправок. Для ответственных процедур статус услуги сверяют с официальными извещениями.'],
